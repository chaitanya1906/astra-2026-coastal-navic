/**
 * Finds the nearest coastal city or region from any (lat, lng) on Earth.
 * If distance exceeds maxDistanceDeg (~800km), returns null indicating open ocean.
 */
export function findNearestCoastalHub(
  lat: number,
  lng: number,
  maxDistanceDeg: number = 10.0
): { location: CoastalLocation; distanceKm: number; isOpenOcean: boolean } {
  let closest = GLOBAL_COASTAL_DATASET[0];
  let minDistanceSq = Infinity;

  for (const item of GLOBAL_COASTAL_DATASET) {
    const dLat = item.lat - lat;
    // Account for longitudinal compression
    const cosLat = Math.cos((lat * Math.PI) / 180);
    const dLng = (item.lng - lng) * cosLat;
    const distSq = dLat * dLat + dLng * dLng;

    if (distSq < minDistanceSq) {
      minDistanceSq = distSq;
      closest = item;
    }
  }

  const degDist = Math.sqrt(minDistanceSq);
  const distanceKm = Math.round(degDist * 111.32);
  const isOpenOcean = degDist > maxDistanceDeg;

  return {
    location: closest,
    distanceKm,
    isOpenOcean,
  };
}
